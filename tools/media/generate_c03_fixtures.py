"""Generate the project-owned C03 stereo grid and tone using FFmpeg.

Requires an FFmpeg build with drawtext and a local TrueType font. Encoding bytes
vary with FFmpeg/libx264 and the selected font; the checked-in original used Arial.
"""

from __future__ import annotations

import argparse
import hashlib
import json
import os
from pathlib import Path
import subprocess

ROOT = Path(__file__).resolve().parents[2]


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--ffmpeg", default=os.environ.get("IMMIVIO_FFMPEG", "ffmpeg"))
    parser.add_argument("--font", required=True, type=Path)
    parser.add_argument(
        "--output", type=Path, default=ROOT / "app/godot/media/c03_sbs_grid.mp4"
    )
    parser.add_argument(
        "--manifest", type=Path, default=ROOT / "tests/fixtures/c03_sbs_grid.json"
    )
    args = parser.parse_args()
    if not args.font.is_file():
        parser.error(
            "--font must name an existing TrueType font (Arial for the original labels)"
        )
    available_filters = subprocess.check_output(
        [args.ffmpeg, "-hide_banner", "-filters"], text=True, stderr=subprocess.DEVNULL
    )
    if "drawtext" not in available_filters:
        parser.error(
            "Selected FFmpeg lacks drawtext; supply --ffmpeg with a build including FreeType/HarfBuzz"
        )
    font = (
        str(args.font.resolve())
        .replace("\\", "/")
        .replace(":", "\\:")
        .replace("'", "'\\''")
    )
    filters = [
        "drawbox=x=0:y=0:w=960:h=1080:color=red:t=fill",
        "drawbox=x=960:y=0:w=960:h=1080:color=blue:t=fill",
        "drawgrid=w=240:h=180:t=4:c=white@0.6",
    ]
    for text, x, y, size, color in [
        ("LEFT - TOP", 80, 60, 72, "white"),
        ("RIGHT - TOP", 1040, 60, 72, "white"),
        ("BOTTOM", 80, 920, 72, "yellow"),
        ("BOTTOM", 1040, 920, 72, "yellow"),
        ("FRAME %{n}", 300, 480, 60, "white"),
        ("FRAME %{n}", 1260, 480, 60, "white"),
    ]:
        filters.append(
            f"drawtext=fontfile='{font}':text='{text}':x={x}:y={y}:fontsize={size}:fontcolor={color}"
        )
    args.output.parent.mkdir(parents=True, exist_ok=True)
    subprocess.run(
        [
            args.ffmpeg,
            "-hide_banner",
            "-loglevel",
            "error",
            "-y",
            "-f",
            "lavfi",
            "-i",
            "color=c=black:s=1920x1080:r=30:d=6",
            "-f",
            "lavfi",
            "-i",
            "sine=frequency=440:sample_rate=48000:duration=6",
            "-vf",
            ",".join(filters),
            "-c:v",
            "libx264",
            "-preset",
            "fast",
            "-crf",
            "20",
            "-pix_fmt",
            "yuv420p",
            "-profile:v",
            "high",
            "-color_primaries",
            "bt709",
            "-color_trc",
            "bt709",
            "-colorspace",
            "bt709",
            "-c:a",
            "aac",
            "-b:a",
            "96k",
            "-movflags",
            "+faststart",
            "-shortest",
            str(args.output),
        ],
        check=True,
    )
    subprocess.run(
        [
            args.ffmpeg,
            "-hide_banner",
            "-loglevel",
            "error",
            "-i",
            str(args.output),
            "-f",
            "null",
            "-",
        ],
        check=True,
    )
    manifest = json.loads(args.manifest.read_text(encoding="utf-8-sig"))
    manifest.update(
        source="Synthetic red/blue labelled grid generated by tools/media/generate_c03_fixtures.py",
        file=os.path.relpath(args.output, ROOT).replace("\\", "/"),
        bytes=args.output.stat().st_size,
        sha256=hashlib.sha256(args.output.read_bytes()).hexdigest(),
        ffmpeg=subprocess.check_output(
            [args.ffmpeg, "-version"], text=True
        ).splitlines()[0],
        android_validation="not_run",
    )
    args.manifest.parent.mkdir(parents=True, exist_ok=True)
    args.manifest.write_text(
        json.dumps(manifest, ensure_ascii=False, indent=2) + "\n", encoding="utf-8"
    )
    print(f"Generated and decoded: {args.output}")


if __name__ == "__main__":
    main()
